def seed_initial_knowledge(db: Session, rag_service):
    # Перезаписываем справочник, если добавились новые статьи
    count = db.query(KnowledgeArticle).count()
    if count != len(INITIAL_ARTICLES):
        db.query(KnowledgeArticle).delete()
        db.commit()
        for item in INITIAL_ARTICLES:
            db.add(KnowledgeArticle(**item))
        db.commit()

    rag_service.sync_sql_to_vector_db(db)