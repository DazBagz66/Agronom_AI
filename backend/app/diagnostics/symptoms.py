def disease_key(title):
    """Приводим разные названия одной болезни к общему ключу."""
    text = title.casefold().replace("ё", "е")
    for word, key in [
        ("розовая гниль", "pink_rot"),
        ("гниль клубня — тип", "tuber_rot"),
        ("фитофтор", "late_blight"), ("альтернар", "alternaria"),
        ("обыкновенн", "common_scab"), ("фузари", "fusarium"),
        ("кольцев", "ring_rot"), ("бурая бактери", "brown_rot"),
        ("черная ножка", "blackleg"), ("ризоктон", "rhizoctonia"),
        ("серебрист", "silver_scurf"), ("фомоз", "phoma"), ("вертиц", "verticillium"),
    ]:
        if word in text:
            return key
    return title.casefold()


