def positive_symptoms(text):
    """Исключаем некоторые отрицания, например «нет пятен»."""
    text = text.casefold().replace("ё", "е")
    text = re.sub(r"\bсил\s+ьно\b", "сильно", text)
    text = re.sub(r"\bне\s+(?:мягк\w*|рыхл\w*|размягч\w*|гни\w*|увяда\w*|вян\w*)", " ", text)
    return re.sub(r"\b(?:без|нет|отсутствуют|не обнаружены)\b[^.,;!?]*(?=[.,;!?]|$)", " ", text)


def symptom_evidence(text, key):
    """Считаем баллы только при совпадении нескольких групп признаков."""
    positive = positive_symptoms(text)
    if key == "tuber_rot" and not re.search(r"рыхл|размягч|мягк|слиз|трух|рассып|разруш|гни", positive):
        return 0., []
    matches = [(weight, label) for pattern, weight, label in PROFILES.get(key, [])
               if re.search(pattern, positive)]
    if len(matches) < 2:
        return 0., []
    score = min(.96, .20 + sum(weight for weight, _ in matches))
    # Итог — баллы совпавших признаков, а не подтверждённая вероятность болезни.
    return score, [label for _, label in matches]
